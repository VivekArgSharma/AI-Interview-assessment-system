"""
PRISM Dataset Generator (PRD Section 16.1)
Generates 300+ realistic rated responses across Technical and Non-Technical roles
with at least 2 simulated trained human raters, acoustic prosody metrics,
descriptive video features, and candidate demographic/subgroup labels.
"""

import os
import json
import random
import numpy as np
from typing import Dict, Any, List

def generate_multimodal_dataset(output_path: str = "ml/data/interview_dataset.json", sample_count: int = 320):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    random.seed(42)
    np.random.seed(42)

    tech_questions = [
        "A payment processing worker is emitting duplicate journal entries under network timeout retry. How do you isolate the root cause?",
        "How do you ensure non-idempotent HTTP API clients do not cause double-charging during connection resets?",
        "Walk me through your debugging methodology when reproduction steps are intermittent in production.",
        "What are the latency versus consistency trade-offs between an in-memory deduplication set and a distributed key-value store?",
        "How would you design automated unit and integration tests to verify retry idempotency under simulated chaos?"
    ]

    non_tech_questions = [
        "A high-value enterprise client has waited 3 weeks for an agreed refund and is furious on the phone. How do you handle them?",
        "A hesitant parent is skeptical of your AI learning course, claiming children already spend too much time on screens. How do you respond?",
        "A senior colleague accuses you of publicly blaming them for a missed sprint handoff. How do you de-escalate?",
        "How do you uncover hidden organizational budget constraints when a prospect gives a generic pricing objection?",
        "How do you transition a hesitant prospect into a concrete, scheduled commitment without aggressive pressure?"
    ]

    subgroups = ["Tier-1 Universities", "Tier-2/3 Universities", "Non-traditional / Self-taught", "Disability Accommodations (Text Fallback)"]

    dataset = []

    for i in range(sample_count):
        role_type = "technical" if i % 2 == 0 else "non_technical"
        role_title = "Distributed Systems Engineer" if role_type == "technical" else "Client Escalation Specialist"
        question = random.choice(tech_questions if role_type == "technical" else non_tech_questions)
        subgroup = random.choice(subgroups)

        # Baseline candidate capability (1.0 - 5.0)
        latent_skill = float(np.clip(np.random.normal(3.5, 0.8), 1.2, 4.9))

        # Text answers generated by capability
        if latent_skill >= 4.0:
            if role_type == "technical":
                transcript = (
                    "I isolate the failure boundary by checking DB records first, then verifying application accumulator state. "
                    "The defect is caused by the accumulator list mutating in outer loop scope across network retries without deduplication. "
                    "I replace the mutable list with an idempotent set keyed by unique idempotency token, reset state per attempt, "
                    "and write a unit test mocking ConnectionError to assert zero duplicates."
                )
            else:
                transcript = (
                    "I begin by validating their emotional frustration completely and apologizing sincerely for the delay before citing any policy. "
                    "I ask open-ended discovery questions to pinpoint what immediate outcome they need today, take personal ownership "
                    "to initiate the refund reversal directly, and schedule a confirmation callback with a reference ID."
                )
        elif latent_skill >= 2.8:
            if role_type == "technical":
                transcript = (
                    "I would check the application logs to see why records are duplicated. If the database is fine, the issue is likely "
                    "in the retry logic. I would fix the retry loop so it doesn't add records twice and run tests locally."
                )
            else:
                transcript = (
                    "I understand they are angry, so I would tell them I am looking into it and explain that our standard refund SLA is 10 business days. "
                    "I would try to offer them a partial credit or ask for their receipt to speed up the process."
                )
        else:
            if role_type == "technical":
                transcript = "I think it's a database bug or maybe cache issue. I would restart the server and see if it goes away."
            else:
                transcript = "I would tell them our company policy states refunds take 3 weeks, so they just have to wait."

        # Acoustic Prosody Features
        speech_wpm = float(np.clip(np.random.normal(138.0, 16.0), 105.0, 175.0))
        articulation_wpm = speech_wpm + float(np.random.uniform(10.0, 20.0))
        pause_count = int(np.clip(np.random.poisson(4), 1, 10))
        total_pause_sec = float(np.clip(pause_count * np.random.uniform(0.6, 1.2), 0.8, 8.0))
        filler_count = int(np.clip(np.random.poisson(2 if latent_skill > 3.0 else 5), 0, 12))
        pitch_mean_hz = float(np.random.uniform(120.0, 210.0))
        pitch_std_hz = float(np.random.uniform(16.0, 32.0))

        # Descriptive Video Features (default weight 0)
        framing_stability = float(np.clip(np.random.normal(0.92, 0.05), 0.70, 1.0))
        gaze_at_camera_ratio = float(np.clip(np.random.normal(0.85, 0.08), 0.60, 0.98))

        # Simulated Human Raters (Section 16.1: 2 trained raters with minor rater variance)
        rater_1_score = float(np.clip(latent_skill + np.random.normal(0, 0.18), 1.0, 5.0))
        rater_2_score = float(np.clip(latent_skill + np.random.normal(0, 0.18), 1.0, 5.0))
        ground_truth_score = round((rater_1_score + rater_2_score) / 2.0, 2)

        sample = {
            "id": f"sample_{i+1:03d}",
            "role_type": role_type,
            "role_title": role_title,
            "subgroup": subgroup,
            "question": question,
            "transcript": transcript,
            "acoustic_features": {
                "speaking_rate_wpm": round(speech_wpm, 1),
                "articulation_rate_wpm": round(articulation_wpm, 1),
                "pause_count": pause_count,
                "total_pause_seconds": round(total_pause_sec, 2),
                "filler_count": filler_count,
                "pitch_mean_hz": round(pitch_mean_hz, 1),
                "pitch_std_hz": round(pitch_std_hz, 1)
            },
            "video_features": {
                "framing_stability": round(framing_stability, 3),
                "gaze_at_camera_ratio": round(gaze_at_camera_ratio, 3)
            },
            "ratings": {
                "rater_1": round(rater_1_score, 2),
                "rater_2": round(rater_2_score, 2),
                "consensus_ground_truth": ground_truth_score
            }
        }
        dataset.append(sample)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2)

    print(f"[OK] Successfully generated {len(dataset)} multimodal interview samples to {output_path}")

if __name__ == "__main__":
    generate_multimodal_dataset()
